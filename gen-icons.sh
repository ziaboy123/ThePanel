#!/usr/bin/env bash
# Regenerate the icon fonts (src/icons_28.c, src/icons_racing_40.c) with
# lv_font_conv, then put the third-party licence header back on top of each
# (lv_font_conv overwrites the whole file). To add an icon, add its codepoint
# to the right -r list below and a #define to src/icons.h.
#
# The glyphs come from font files, so the output is a converted ("Modified")
# version of those fonts and stays under their licences: Font Awesome Free's
# fonts under the SIL OFL 1.1, Material Design Icons' webfont under
# Apache-2.0. See THIRD_PARTY_NOTICES.md. The LVGL font names (icons_28,
# icons_racing_40) must not use the reserved name "Font Awesome".
set -euo pipefail
cd "$(dirname "$0")"

# The packages go in a throwaway folder, linked in as ./node_modules so the
# paths lv_font_conv records in each file's "Opts:" line stay relative.
[ -e node_modules ] && { echo "./node_modules already exists - move it out of the way first."; exit 1; }
work=$(mktemp -d)
trap 'rm -rf "$work"; rm -f node_modules' EXIT
npm install --prefix "$work" --silent --no-audit --no-fund \
  @fortawesome/fontawesome-free@6 @mdi/font@7 lv_font_conv@1
ln -s "$work/node_modules" node_modules
conv="$work/node_modules/.bin/lv_font_conv"
FA=node_modules/@fortawesome/fontawesome-free/webfonts
MDI=node_modules/@mdi/font/fonts/materialdesignicons-webfont.ttf

"$conv" --bpp 4 --size 28 --no-compress --format lvgl --lv-include lvgl.h --lv-font-name icons_28 \
  --font "$FA/fa-solid-900.ttf" -r 0xf625,0xf233,0xf6ff,0xf1de,0xf390,0xf26c,0xf3ed,0xf2f9,0xf3fa \
  --font "$FA/fa-brands-400.ttf" -r 0xf09b \
  --font "$MDI" -r 0xF0373,0xF07AC,0xF0821 \
  -o src/icons_28.c
"$conv" --bpp 4 --size 40 --no-compress --format lvgl --lv-include lvgl.h --lv-font-name icons_racing_40 \
  --font "$MDI" -r 0xF07AC \
  -o src/icons_racing_40.c

FA_VERSION=$(node -p "require('./node_modules/@fortawesome/fontawesome-free/package.json').version")
MDI_VERSION=$(node -p "require('./node_modules/@mdi/font/package.json').version")

fa_notice=" *   - Font Awesome Free $FA_VERSION (fa-solid-900.ttf, fa-brands-400.ttf)
 *     Copyright (c) 2024 Fonticons, Inc. (https://fontawesome.com)
 *     with Reserved Font Name \"Font Awesome\".
 *     SIL Open Font License, Version 1.1.
"
mdi_notice=" *   - Material Design Icons webfont $MDI_VERSION (materialdesignicons-webfont.ttf)
 *     by Pictogrammers (https://pictogrammers.com).
 *     Apache License, Version 2.0.
"

header() {  # $1 = file, $2 = what's in it
  local tmp
  tmp=$(mktemp)
  {
    echo "/*******************************************************************************"
    echo " * Icon font for The Panel, generated by gen-icons.sh with lv_font_conv."
    echo " * It is a modified version of the fonts below: a subset of their glyphs,"
    echo " * converted to an LVGL bitmap font. It stays under those fonts' licences"
    echo " * (not this repository's MIT licence). Full texts:"
    echo " * THIRD_PARTY_NOTICES.md."
    echo " *"
    printf '%s' "$2"
    echo " ******************************************************************************/"
    echo
    cat "$1"
  } > "$tmp"
  mv "$tmp" "$1"
}
header src/icons_28.c "$fa_notice$mdi_notice"
header src/icons_racing_40.c "$mdi_notice"
echo "Regenerated src/icons_28.c and src/icons_racing_40.c (Font Awesome Free $FA_VERSION, MDI $MDI_VERSION)."
